#!/usr/bin/env python3
"""Copy spec/scripts into each port so packages ship the exact same bytes.

Usage: sync_assets.py [--check]   (--check fails when a generated copy is stale)
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LUA = ROOT / "spec/scripts/redis/hit.lua"
SQL = ROOT / "spec/scripts/postgres/001_v1.sql"
VERSION = ROOT / "spec/VERSION"
TS_TARGET = ROOT / "ts/src/generated/assets.ts"
PY_TARGET = ROOT / "python/src/omnilimit/_generated.py"


def render() -> dict[Path, str]:
    lua = LUA.read_bytes()
    sql = SQL.read_bytes()
    version = VERSION.read_text(encoding="utf-8").strip()
    sha1 = hashlib.sha1(lua).hexdigest()  # noqa: S324 - Redis identifies scripts by SHA-1
    lua_text = json.dumps(lua.decode("utf-8"))
    sql_text = json.dumps(sql.decode("utf-8"))
    return {
        TS_TARGET: (
            "// GENERATED by tools/sync_assets.py from spec/scripts. Do not edit.\n"
            f"export const SPEC_VERSION = {json.dumps(version)};\n"
            f"export const REDIS_HIT_SHA1 = {json.dumps(sha1)};\n"
            f"export const REDIS_HIT_LUA = {lua_text};\n"
            f"export const POSTGRES_MIGRATION_SQL = {sql_text};\n"
        ),
        PY_TARGET: (
            "# GENERATED by tools/sync_assets.py from spec/scripts. Do not edit.\n"
            f"SPEC_VERSION = {json.dumps(version)}\n"
            f"REDIS_HIT_SHA1 = {json.dumps(sha1)}\n"
            f"REDIS_HIT_LUA = {lua_text}\n"
            f"POSTGRES_MIGRATION_SQL = {sql_text}\n"
        ),
    }


def main() -> int:
    rendered = render()
    if "--check" in sys.argv[1:]:
        stale = [
            path
            for path, content in rendered.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale: run tools/sync_assets.py", file=sys.stderr)
        if stale:
            return 1
        print("assets in sync")
        return 0
    for path, content in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
