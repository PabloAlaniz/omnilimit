#!/usr/bin/env python3
"""Copy spec/scripts into each port so packages ship the exact same bytes.

Usage: sync_assets.py [--check]   (--check fails when a generated copy is stale)
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LUA = ROOT / "spec/scripts/redis/hit.lua"
SQL = ROOT / "spec/scripts/postgres/001_v1.sql"
VERSION = ROOT / "spec/VERSION"
TARGET = ROOT / "ts/src/generated/assets.ts"


def render() -> str:
    lua = LUA.read_bytes()
    sql = SQL.read_bytes()
    version = VERSION.read_text(encoding="utf-8").strip()
    return (
        "// GENERATED by tools/sync_assets.py from spec/scripts. Do not edit.\n"
        f"export const SPEC_VERSION = {json.dumps(version)};\n"
        f"export const REDIS_HIT_SHA1 = {json.dumps(hashlib.sha1(lua).hexdigest())};\n"
        f"export const REDIS_HIT_LUA = {json.dumps(lua.decode('utf-8'))};\n"
        f"export const POSTGRES_MIGRATION_SQL = {json.dumps(sql.decode('utf-8'))};\n"
    )


def main() -> int:
    content = render()
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print(f"{TARGET.relative_to(ROOT)} is stale: run tools/sync_assets.py", file=sys.stderr)
            return 1
        print("assets in sync")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
